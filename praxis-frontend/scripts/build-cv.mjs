import { build } from "esbuild";
import { createRequire } from "node:module";
import { copyFile, mkdir, writeFile } from "node:fs/promises";
const require = createRequire(import.meta.url);
await mkdir("public/cv", { recursive: true });
await copyFile(
  require.resolve("@techstark/opencv-js"),
  "public/cv/opencv-4.12.0.js",
);
await copyFile(
  require.resolve("@techstark/opencv-js/LICENSE"),
  "public/cv/LICENSE.opencv-js",
);
await build({
  entryPoints: ["lib/cv/geometry.worker.ts"],
  outfile: "public/cv/geometry-worker.js",
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "es2020",
  sourcemap: false,
});
await writeFile(
  "public/cv/README.txt",
  "Generated by npm run build:cv. OpenCV.js 4.12.0-release.1; see LICENSE.opencv-js. No images or credentials are included.\n",
);
